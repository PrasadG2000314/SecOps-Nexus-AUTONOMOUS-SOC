"""
Zero Trust Cryptographic Security Layer
Provides HMAC-SHA256 signature verification, timing-safe validation,
token signing, and strict AI prompt sanitization.
"""
import hmac
import hashlib
import re
from typing import Optional
from config import settings

# Suspicious patterns associated with prompt injection or command escapes
INJECTION_PATTERNS = [
    r"(?i)ignore\s+(all\s+)?(previous|prior|above)\s+instructions",
    r"(?i)system\s*:\s*you\s+are",
    r"(?i)disregard\s+(all\s+)?safety\s+guidelines",
    r"(?i)as\s+an\s+unfiltered\s+(ai|agent)",
    r"(?i)developer\s+mode\s+enabled",
    r"(?i)bypass\s+all\s+restrictions",
    r"(?i)<\s*script[^>]*>.*?<\s*/\s*script\s*>",
    r"(?i)\brm\s+-rf\s+/",
    r"(?i)\bmkfs\b"
]

def generate_hmac_signature(payload_bytes: bytes, secret: Optional[str] = None) -> str:
    """Generates an HMAC-SHA256 signature for a payload."""
    sec = (secret or settings.WEBHOOK_HMAC_SECRET).encode("utf-8")
    return hmac.new(sec, payload_bytes, hashlib.sha256).hexdigest()

def verify_hmac_signature(payload_bytes: bytes, signature_header: Optional[str], secret: Optional[str] = None) -> bool:
    """
    Verifies that the incoming webhook payload was signed with the shared HMAC secret.
    Uses timing-attack resistant hmac.compare_digest.
    """
    if not signature_header:
        return False
    
    # Strip any prefix like 'sha256=' if provided
    clean_signature = signature_header.strip()
    if clean_signature.startswith("sha256="):
        clean_signature = clean_signature.split("=", 1)[1]
    
    expected_signature = generate_hmac_signature(payload_bytes, secret)
    return hmac.compare_digest(expected_signature, clean_signature)

def sign_approval_decision(alert_id: str, approver_name: str, approver_role: str, secret: Optional[str] = None) -> str:
    """
    Creates a tamper-evident cryptographic signature for Human-In-The-Loop approvals.
    """
    sec = (secret or settings.WEBHOOK_HMAC_SECRET).encode("utf-8")
    message = f"HITL-APPROVAL:{alert_id}:{approver_name}:{approver_role}".encode("utf-8")
    return hmac.new(sec, message, hashlib.sha256).hexdigest()

def verify_approval_signature(alert_id: str, approver_name: str, approver_role: str, signature: str, secret: Optional[str] = None) -> bool:
    """Verifies that the approval token was generated by an authorized agent."""
    expected = sign_approval_decision(alert_id, approver_name, approver_role, secret)
    return hmac.compare_digest(expected, signature)

def sanitize_ai_prompt_input(raw_text: str, max_length: int = 4000) -> str:
    """
    Sanitizes user/scanner input before passing into the Gemini Security Reasoning Prompt.
    Defends against Prompt Injection attacks and oversized buffer denial-of-service.
    """
    if not raw_text:
        return ""
    
    # Truncate to maximum acceptable analysis window
    text = raw_text[:max_length]
    
    # Defang obvious prompt injection and escape strings
    for pattern in INJECTION_PATTERNS:
        text = re.sub(pattern, "[DEFANGED_POTENTIAL_INJECTION_PAYLOAD]", text)
        
    return text.strip()

# ==========================================
# Secret Masking & Redaction Defenses
# ==========================================
SECRET_PATTERNS = [
    (re.compile(r"""(?i)(AKIA[0-9A-Z]{16})"""), "AKIA...[REDACTED_AWS_KEY]"),
    (re.compile(r"""(?i)(ghp_[a-zA-Z0-9]{36}|github_pat_[a-zA-Z0-9_]{82})"""), "ghp_...[REDACTED_GITHUB_TOKEN]"),
    (re.compile(r"""(?i)(sk-[a-zA-Z0-9]{20,}|sk-proj-[a-zA-Z0-9_\-]{30,})"""), "sk-...[REDACTED_API_KEY]"),
    (re.compile(r"""(?i)(['"])(password|passwd|secret|api_key|auth_token)(['"]\s*[:=]\s*['"])([^'"]{4,})(['"])"""), r"\1\2\3[REDACTED_SECRET]\5"),
    (re.compile(r"""-----BEGIN [A-Z ]+ PRIVATE KEY-----[\s\S]+?-----END [A-Z ]+ PRIVATE KEY-----"""), "[REDACTED_PRIVATE_KEY]")
]

def mask_secret(secret_str: Optional[str], visible_prefix: int = 4, visible_suffix: int = 4) -> str:
    """
    Masks a sensitive API key or secret token for safe display.
    Example: 'AKIA1234567890ABCDEF' -> 'AKIA************CDEF'
    """
    if not secret_str:
        return ""
    s_len = len(secret_str)
    if s_len <= (visible_prefix + visible_suffix):
        return "*" * s_len
    
    masked_middle = "*" * (s_len - visible_prefix - visible_suffix)
    return f"{secret_str[:visible_prefix]}{masked_middle}{secret_str[-visible_suffix:]}"

def redact_sensitive_text(raw_text: str) -> str:
    """
    Scans arbitrary text or code snippets and replaces known API key / credential patterns with safe redacted tokens.
    Guarantees that sensitive secrets are never logged in cleartext or returned in API responses.
    """
    if not raw_text:
        return ""
    
    redacted = raw_text
    for pattern, replacement in SECRET_PATTERNS:
        redacted = pattern.sub(replacement, redacted)
    return redacted
